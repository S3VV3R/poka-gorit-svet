const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
let portrait=true,starts=0,resets=0,update,afterFrame;
const gate={hidden:true},active=new Set(),paused=new Set(['AlreadyPaused']);
const sceneFor=key=>({scene:{key,pause(){active.delete(key);paused.add(key);}}});
const game={scene:{getScenes(){return [...active].map(sceneFor);},pause(key){active.delete(key);paused.add(key);},isPaused:key=>paused.has(key),resume(key){paused.delete(key);active.add(key);}}};
game.events={on(name,fn){if(name==='poststep')afterFrame=fn;}};
const window={matchMedia:()=>({matches:portrait,addEventListener(){}}),addEventListener(name,fn){if(name==='resize')update=fn;}};
const context={window,document:{getElementById:()=>gate,body:{classList:{toggle(){}}}},DeviceProfile:{refresh(){return this.current={portraitBlocked:portrait,label:'Телефон'};}},AdaptiveUI:{releaseControls(){resets++;}},Audio:{}};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root,'js/core/orientation-gate.js'),'utf8'),context);
const orientation=vm.runInContext('OrientationGate',context);
orientation.startWhenReady(()=>{starts++;window.__phaserGame=game;active.add('World');active.add('UI');});
assert.equal(starts,0,'portrait must not start the engine');assert.equal(gate.hidden,false);
portrait=false;update();assert.equal(starts,1);assert.equal(gate.hidden,true);
update();assert.equal(starts,1,'repeated resize must not create another game');
portrait=true;update();assert.equal(active.size,0);assert.ok(paused.has('World'));assert.ok(paused.has('UI'));
active.add('LoadedWhilePortrait');afterFrame();assert.ok(paused.has('LoadedWhilePortrait'),'loading cannot start a scene behind the portrait warning');
portrait=false;update();assert.ok(active.has('World'));assert.ok(active.has('UI'));
assert.ok(paused.has('AlreadyPaused'),'orientation must not resume unrelated paused scenes');assert.equal(starts,1);
assert.ok(resets>=4,'rotation clears held touch controls');
const version=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8')).version;
assert.ok(fs.readFileSync(path.join(root,'index.html'),'utf8').includes('>'+`v${version}`+'<'));
assert.ok(fs.readFileSync(path.join(root,'CHANGELOG.md'),'utf8').includes('v'+version));
console.log('PASS: portrait blocks startup, landscape starts once, rotation pauses/resumes only owned scenes, version matches');
